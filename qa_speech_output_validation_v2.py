    def generate_speech_audio(self, text: str, language: str = "en", emotion: str = "neutral") -> Optional[bytes]:
        """Generate realistic speech audio using TTS."""
        if not self.tts_service:
            return None
        
        try:
            request = TtsSynthesisRequest(
                text=text,
                language=language,
                emotion=emotion
            )
            wav_bytes = self.tts_service.synthesize(request)
            
            # Verify output
            if len(wav_bytes) > 100:  # Should be more than empty WAV
                return wav_bytes
            else:
                print(f"    [WARN] TTS generated empty audio for: '{text}'")
                return None
        except Exception as e:
            print(f"    [WARN] TTS synthesis failed: {e}")
            return None
    
    def analyze_audio_file(self, file_path: Path) -> Dict[str, Any]:
        """Analyze audio file properties."""
        if not file_path.exists():
            return {
                "exists": False,
                "error": "File does not exist"
            }
        
        file_size = file_path.stat().st_size
        
        try:
            # Read using soundfile
            audio_data, sample_rate = sf.read(file_path)
            
            # Handle mono/stereo
            if audio_data.ndim == 2:
                audio_data = audio_data.mean(axis=1)
            
            duration = len(audio_data) / sample_rate
            rms = float(np.sqrt(np.mean(np.square(audio_data))))
            peak = float(np.max(np.abs(audio_data)))
            
            # Check if silent
            is_silent = rms < 1e-5
            
            # Calculate approximate speech rate (zero crossings)
            zero_crossings = np.sum(np.abs(np.diff(np.sign(audio_data)))) / 2
            zcr = zero_crossings / duration if duration > 0 else 0
            
            return {
                "exists": True,
                "file_size_bytes": file_size,
                "file_size_kb": round(file_size / 1024, 2),
                "duration_sec": round(duration, 3),
                "sample_rate": sample_rate,
                "rms": round(rms, 6),
                "peak": round(peak, 4),
                "is_silent": is_silent,
                "zcr": round(zcr, 2),
                "waveform_valid": peak > 0.01 and not is_silent,
                "audio_channels": 1 if audio_data.ndim == 1 else audio_data.shape[1],
            }
        except Exception as e:
            return {
                "exists": True,
                "file_size_bytes": file_size,
                "error": f"Failed to analyze: {str(e)}"
            }
    
