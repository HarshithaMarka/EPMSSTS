        print("TEST 5: ROUND-TRIP PIPELINE VERIFICATION")
        print("="*80)
        print("Verifying: Complete EN->TE->EN->TE pipeline")
        
        round_trip_tests = []
        translation_pairs = [
            ("en", "te", "en", "English -> Telugu -> English"),
            ("en", "hi", "en", "English -> Hindi -> English"),
        ]
        
        for src, mid, target, description in translation_pairs:
            print(f"\n  [{description}]")
            
            try:
                test_text = "Hello world, this is a test"
                
                # Generate source audio
                source_audio = self.generate_speech_audio(test_text, language=src)
                
                if not source_audio:
                    round_trip_tests.append({
                        "translation_pair": description,
                        "status": "skip",
                        "reason": "Source audio generation failed"
                    })
                    continue
                
                # First hop: src -> mid
                print(f"    Step 1: {src.upper()} -> {mid.upper()}")
                files = {"file": ("test.wav", source_audio, "audio/wav")}
                data = {"target_lang": mid}
                
                response1 = await client.post(
                    "/process/speech-to-speech",
                    files=files,
                    data=data,
                    timeout=120.0
                )
                
                if response1.status_code != 200:
                    round_trip_tests.append({
                        "translation_pair": description,
                        "status": "fail",
                        "step": "first_translation"
                    })
                    continue
                
                result1 = response1.json()
                translated_mid = result1.get("translated_text", "")
                session_id_1 = result1.get("session_id", "")
                
                # Get intermediate audio
                outputs_dir = Path(__file__).parent / "outputs"
                audio_file_1 = outputs_dir / f"{session_id_1}.wav"
                mid_audio = audio_file_1.read_bytes() if audio_file_1.exists() else None
                
                if not mid_audio:
                    round_trip_tests.append({
                        "translation_pair": description,
                        "status": "fail",
                        "step": "intermediate_audio_generation"
                    })
                    continue
                
                # Second hop: mid -> target
                print(f"    Step 2: {mid.upper()} -> {target.upper()}")
                files = {"file": ("test.wav", mid_audio, "audio/wav")}
                data = {"target_lang": target}
                
                response2 = await client.post(
                    "/process/speech-to-speech",
                    files=files,
                    data=data,
                    timeout=120.0
                )
                
                if response2.status_code != 200:
                    round_trip_tests.append({
                        "translation_pair": description,
                        "status": "fail",
                        "step": "second_translation"
                    })
                    continue
                
                result2 = response2.json()
                final_audio_path = outputs_dir / f"{result2.get('session_id', '')}.wav"
                final_audio_analysis = self.analyze_audio_file(final_audio_path)
                
                # Checks
                checks = {
                    "intermediate_translation_valid": len(translated_mid.strip()) > 0,
                    "intermediate_audio_valid": audio_file_1.exists() and audio_file_1.stat().st_size > 44,
                    "final_audio_valid": final_audio_analysis.get("waveform_valid", False),
                    "full_pipeline_executed": result2.get("detected_language") is not None,
                }
                
                all_passed = all(checks.values())
                
                for check, passed in checks.items():
                    status_str = "[✓]" if passed else "[✗]"
                    print(f"    {status_str} {check}")
                
                round_trip_tests.append({
                    "translation_pair": description,
                    "status": "pass" if all_passed else "partial",
                    "checks": checks,
                    "intermediate": translated_mid[:50],
                })
                
                print(f"    Result: {'[PASS]' if all_passed else '[PARTIAL]'}")
                
            except Exception as e:
                print(f"    [ERROR] {e}")
                round_trip_tests.append({
                    "translation_pair": description,
                    "status": "fail",
                    "error": str(e)
                })
        
        self.results["round_trip_tests"] = {
            "test_cases": round_trip_tests,
            "total": len(translation_pairs),
            "passed": sum(1 for r in round_trip_tests if r["status"] == "pass"),
        }
    
